# -*- coding: utf-8 -*-
"""
Тарифи. Джерело правди для сервера.

Ті самі числа продубльовані в static/js/priceCalculator.js — інакше
калькулятор не працював би без запиту на сервер. Дублювання свідоме, але
небезпечне: якщо цифри розійдуться, сторінка напрямку й калькулятор
назвуть різну ціну за той самий рейс. Тому в routetest.py є перевірка,
яка вичитує константи з JS і порівнює з цими.

ТРИ МОДЕЛІ, бо це три різні послуги.

1. ПО КИЄВУ Й ОБЛАСТІ машина переважно СТОЇТЬ — чекає, поки завантажать
   і розвантажать. Рахунок за годинами. Скільки триватиме завантаження,
   наперед не знає ніхто, тому підсумок не рахуємо: показуємо ставку.

2. МІЖМІСЬКИЙ РЕЙС ПО УКРАЇНІ — кілометри, машина їде. Ціна за доставку
   в один бік; порожній зворотний пробіг уже закладений у ставку.
   Якщо клієнту треба ще й привезти щось назад, зворотний рейс коштує
   чверть від ціни «туди» — машина однаково їде цим шляхом.

3. ЗАКОРДОН — теж кілометри, але в євро й за ПОВНИЙ пробіг (туди й
   назад), бо через кордон порожній зворотний рейс не окупається нічим.
   Захід Європи дорожчий: дорожче пальне й платні автобани.
"""

# ── 1. Погодинно: Київ і область ────────────────────────────────────────
LOCAL_HOURLY = 799        # грн/год
LOCAL_FEED = 799          # подача, грн
LOCAL_MIN_HOURS = 2

# ── 2. Покілометрово: міжміські по Україні ──────────────────────────────
INTERCITY_PER_KM = 37     # грн/км, за відстань в один бік
INTERCITY_MIN = 20000     # мінімум замовлення, грн
INTERCITY_MIN_FROM_KM = 400   # …діє від цієї відстані; ближче мінімуму немає

# Зворотний рейс із вантажем — чверть від ціни «туди».
RETURN_SHARE = 0.25

# Межа між «область» і «міжмісто»
INTERCITY_FROM_KM = 120

# ── 3. Закордон: євро за повний пробіг (туди й назад) ───────────────────
# Ставки за КІЛОМЕТР ЗАГАЛЬНОГО ПРОБІГУ. Для клієнта, який рахує відстань
# в один бік, це вдвічі більше — обидва числа показуємо явно, щоб не
# виглядало, ніби ціну підняли вдвічі.
ABROAD_ZONES = {
    "east": {
        "per_total_km": 0.60,   # €/км повного пробігу
        "countries": ["country.pl", "country.cz", "country.sk"],
    },
    "west": {
        "per_total_km": 0.70,   # €/км повного пробігу
        "countries": ["country.de", "country.fr", "country.it", "country.es"],
    },
}
ABROAD_CURRENCY = "EUR"


def quote_intercity(km):
    """Вартість міжміського рейсу в один бік і чи спрацював мінімум."""
    total = km * INTERCITY_PER_KM
    min_applied = False
    if km >= INTERCITY_MIN_FROM_KM and total < INTERCITY_MIN:
        total = INTERCITY_MIN
        min_applied = True
    return round(total), min_applied


def quote_intercity_return(km):
    """Ціна рейсу туди й назад: «туди» + чверть від нього."""
    one_way, _ = quote_intercity(km)
    return round(one_way * (1 + RETURN_SHARE))


def quote_abroad(km, zone="east"):
    """
    Вартість закордонного рейсу.

    km — відстань В ОДИН БІК. Платний пробіг удвічі більший, бо машина
    повертається; саме тому ставка вказана за повний пробіг.
    """
    z = ABROAD_ZONES.get(zone) or ABROAD_ZONES["east"]
    total_km = km * 2
    return {
        "eur": round(total_km * z["per_total_km"]),
        "per_total_km": z["per_total_km"],
        "per_one_way_km": round(z["per_total_km"] * 2, 2),
        "total_km": round(total_km),
        "zone": zone,
    }


def local_floor():
    """Найменше, що взагалі може вийти по місту: подача + мінімальні години."""
    return LOCAL_FEED + LOCAL_MIN_HOURS * LOCAL_HOURLY
