"""
Sentry: щоб про поламане дізнавались ми, а не клієнт.

НАВІЩО. Заявка спершу пишеться в SQLite і лише потім іде в Telegram
(routes/contact.py). Якщо Telegram не прийняв, лишається рядок
`logger.error` і запис із `notified = 0` — і більше нічого. О третій ночі
логи ніхто не читає, тому першим про поломку дізнається власник, коли
клієнт спитає, чому йому не передзвонили. Sentry перетворює цей рядок на
сповіщення.

Окремо нічого писати не довелось: інтеграція з logging увімкнена в SDK
типово й підбирає все, що йде рівнем ERROR. Тобто вже наявні
`logger.error` у contact.py і `logger.exception` в обробнику 500 стають
подіями самі собою.

ВИМКНЕНО, ПОКИ НЕМАЄ `SENTRY_DSN`. Без змінної не робиться нічого: ні
імпорту, ні мережі, ні мілісекунди затримки — так само, як з аналітикою.
І навпаки: якщо DSN заданий, а пакета немає, ми про це кажемо в лог.
Мовчазний провал тут найгірший з можливих: власник був би впевнений, що
моніторинг є, і саме тому не дізнався б про поломку.

ЩО ТУДИ НЕ ЇДЕ — головне в цьому файлі.

`max_request_body_size` у Sentry типово "medium", тобто до події
чіпляється ТІЛО ЗАПИТУ. Для нас це означало б, що ім'я, телефон і текст
заявки їдуть на чужий сервер щоразу, коли форма впаде — тобто саме тоді,
коли в тілі точно є персональні дані живої людини. Тому "never": вміст
форми не залишає наш сервер за жодних обставин.

`send_default_pii` лишається вимкненим (це типове значення, але тут воно
записане явно, щоб ніхто не «покращив» файл за прикладом із документації
Sentry — там у прикладі стоїть True).

Трасування не вмикаємо взагалі: `traces_sample_rate` не передається, бо
трейси з'їдають квоту подій, а нам потрібні помилки, не профілювання.
"""

import os


def init_sentry(app):
    """Увімкнути Sentry, якщо він налаштований. Повертає True, якщо увімкнено."""
    dsn = os.getenv("SENTRY_DSN", "").strip()
    if not dsn:
        return False

    try:
        import sentry_sdk
    except ImportError:
        app.logger.warning(
            "SENTRY_DSN заданий, але sentry-sdk не встановлений — "
            "помилки нікуди не йдуть. pip install -r requirements.txt"
        )
        return False

    sentry_sdk.init(
        dsn=dsn,
        # Щоб у Sentry було видно, чи це бойовий сайт, чи локальна машина.
        environment=os.getenv("SENTRY_ENV", "production"),
        # Необов'язково; зручно ставити хеш коміту при деплої.
        release=os.getenv("SENTRY_RELEASE") or None,
        # ↓ два рядки, заради яких існує цей файл
        max_request_body_size="never",
        send_default_pii=False,
    )
    app.logger.info("Sentry увімкнено, оточення «%s»",
                    os.getenv("SENTRY_ENV", "production"))
    return True
